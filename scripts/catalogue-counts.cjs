// Writes the catalogue numbers the welcome page shows, so a first-time visitor on a phone does not
// download the whole curriculum and lab catalogue just to read four counts.
// Run after adding modules or labs: node scripts/catalogue-counts.cjs (tests/check-navigation.cjs fails if stale).
require('./register-typescript.cjs');
for (const extension of ['.css', '.jpg', '.png', '.svg', '.webp']) require.extensions[extension] = module => { module.exports = ''; };
const fs = require('node:fs');
const path = require('node:path');

function catalogueCounts() {
  const { MODULES, ROADMAP } = require('../src/features/curriculum/data/curriculum.ts');
  const { LABS } = require('../src/features/labs/data/labs.ts');
  const modulesByTrack = {};
  for (const step of ROADMAP) if (step.moduleSlug) modulesByTrack[step.track] = (modulesByTrack[step.track] ?? 0) + 1;
  return {
    labs: LABS.length,
    lessons: MODULES.reduce((total, module) => total + module.lessons.length, 0),
    modules: MODULES.length,
    modulesByTrack,
  };
}

const target = path.join(__dirname, '../src/features/marketing/data/catalogueCounts.ts');
const render = counts => '// Generated by scripts/catalogue-counts.cjs. Do not edit by hand.\n'
  + 'export const CATALOGUE_COUNTS = ' + JSON.stringify(counts, null, 2).replace(/"(\w+)":/g, '$1:') + ' as const;\n';

if (require.main === module) {
  fs.writeFileSync(target, render(catalogueCounts()));
  console.log('Wrote ' + path.relative(process.cwd(), target));
}
module.exports = { catalogueCounts, render, target };
